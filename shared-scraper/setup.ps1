# Fleet worker setup - turns a fresh Windows PC into a scraper worker for
# Contabo (mytmtracker.com). Run this ONCE on a new machine, then use
# run-worker.ps1 for every subsequent start/stop.
#
# What this does:
#   1. Installs Python if it's not already on PATH.
#   2. Creates a venv and installs dependencies.
#   3. Asks you to name this machine (becomes its FLEET_MACHINE_KEY).
#   4. Writes both .env files, pointed at Contabo's database.
#   5. Starts the scraper + backend and runs a health check.
#
# Usage:   powershell -ExecutionPolicy Bypass -File .\setup.ps1

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot

# --- Contabo's fixed connection details - same for every worker machine ----
# (not per-machine; only the machine name below is unique per PC)
$PgHost     = '62.146.239.158'
$PgPort     = '5432'
$PgDbName   = 'datascraper'
$PgUser     = 'tmtracker'
$PgPassword = 'Nvgalani@369'
$CoordinatorUrl = 'https://mytmtracker.com'

Write-Host "=== Fleet worker setup ===" -ForegroundColor Cyan
Write-Host ""

# --- 1. Python --------------------------------------------------------------
Write-Host "[1/6] Checking for Python..."
$python = Get-Command python -ErrorAction SilentlyContinue
if (-not $python) {
  Write-Host "  Python not found - downloading and installing (this takes a minute)..." -ForegroundColor Yellow
  $installerUrl = 'https://www.python.org/ftp/python/3.12.7/python-3.12.7-amd64.exe'
  $installerPath = Join-Path $env:TEMP 'python-installer.exe'
  Invoke-WebRequest -Uri $installerUrl -OutFile $installerPath -UseBasicParsing
  Start-Process -FilePath $installerPath -ArgumentList '/quiet', 'InstallAllUsers=1', 'PrependPath=1' -Wait
  Remove-Item $installerPath -Force -ErrorAction SilentlyContinue

  # PATH doesn't refresh in this session automatically - re-check via the
  # machine-scope env var rather than requiring a terminal restart.
  $env:Path = [System.Environment]::GetEnvironmentVariable('Path', 'Machine') + ';' + [System.Environment]::GetEnvironmentVariable('Path', 'User')
  $python = Get-Command python -ErrorAction SilentlyContinue
  if (-not $python) {
    Write-Error "Python installed but not found on PATH yet. Close this window, open a new PowerShell, and re-run setup.ps1."
    exit 1
  }
  Write-Host "  Python installed." -ForegroundColor Green
} else {
  Write-Host "  Found: $($python.Source)" -ForegroundColor Green
}

# --- 2. Virtual environment + dependencies ----------------------------------
Write-Host "[2/6] Setting up virtual environment..."
$venvDir = Join-Path $root '.venv'
if (-not (Test-Path $venvDir)) {
  python -m venv $venvDir
}
$venvPython = Join-Path $venvDir 'Scripts\python.exe'
& $venvPython -m pip install --upgrade pip --quiet
& $venvPython -m pip install -r (Join-Path $root 'requirements.txt') --quiet
& $venvPython -m pip install -r (Join-Path $root 'tm_manager\requirements.txt') --quiet
Write-Host "  Dependencies installed." -ForegroundColor Green

# --- 3. Machine name ---------------------------------------------------------
Write-Host "[3/6] Machine identity"
$envPath = Join-Path $root '.env'
$existingKey = $null
if (Test-Path $envPath) {
  $existingLine = Get-Content $envPath | Where-Object { $_ -match '^FLEET_MACHINE_KEY=' }
  if ($existingLine) { $existingKey = ($existingLine -split '=', 2)[1] }
}
if ($existingKey) {
  Write-Host "  This machine is already set up as '$existingKey'." -ForegroundColor Yellow
  $reuse = Read-Host "  Keep this name? (Y/n)"
  if ($reuse -eq '' -or $reuse -match '^[Yy]') {
    $machineKey = $existingKey
  }
}
if (-not $machineKey) {
  do {
    $machineKey = Read-Host "  Enter a name for this machine (letters/numbers/hyphens only, no spaces)"
    $machineKey = $machineKey.Trim()
    if ($machineKey -notmatch '^[A-Za-z0-9-]+$') {
      Write-Host "  Invalid - use only letters, numbers, and hyphens." -ForegroundColor Red
      $machineKey = $null
    }
  } while (-not $machineKey)
}
Write-Host "  Machine name: $machineKey" -ForegroundColor Green

# --- 4. .env files ------------------------------------------------------------
Write-Host "[4/6] Writing configuration..."

$rootEnv = @"
# Fleet worker - generated by setup.ps1
PG_HOST=$PgHost
PG_PORT=$PgPort
PG_DBNAME=$PgDbName
PG_USER=$PgUser
PG_PASSWORD=$PgPassword

FLEET_MODE_ENABLED=1
FLEET_MACHINE_KEY=$machineKey
FLEET_COORDINATOR_URL=$CoordinatorUrl

# Warm pool is Contabo's own responsibility - keep it off on worker
# machines so this PC never fights Contabo over the same warm-pool
# account's session (see shared-scraper's own .env for why this matters).
WARM_POOL_ENABLED=0
"@
Set-Content -Path $envPath -Value $rootEnv -Encoding UTF8

$tmEnvPath = Join-Path $root 'tm_manager\.env'
$tmEnv = @"
# Fleet worker - generated by setup.ps1
PG_HOST=$PgHost
PG_PORT=$PgPort
PG_DBNAME=$PgDbName
PG_USER=$PgUser
PG_PASSWORD=$PgPassword

SCRAPER_API_BASE_URL=http://127.0.0.1:5001
TM_MANAGER_PORT=5005

FLEET_MODE_ENABLED=1
FLEET_MACHINE_KEY=$machineKey
FLEET_COORDINATOR_URL=$CoordinatorUrl

# AUTO_FETCH_WORKERS is now just a fallback - in fleet mode the scheduler
# sizes worker count to however many accounts are assigned to THIS machine
# on the dashboard (see scheduler.py's _resolve_worker_count), so it scales
# automatically as accounts are added/removed. This value only applies if
# fleet mode is off or the machine isn't registered yet.
AUTO_FETCH_WORKERS=1
# Start conservative - a worker's first run should NOT immediately fire many
# concurrent logins (IP India rate-limits bursts, see the 401-block incident
# from a full-account burst). Raise gradually once this machine has been
# confirmed stable, same caution that applies to however many accounts get
# assigned to it.
AUTO_FETCH_BATCH_SIZE=5
"@
Set-Content -Path $tmEnvPath -Value $tmEnv -Encoding UTF8
Write-Host "  .env files written." -ForegroundColor Green

# --- 5. Start services --------------------------------------------------------
Write-Host "[5/6] Starting services..."

$certifiOut = & $venvPython -c "import certifi; print(certifi.where())" 2>$null
if ($certifiOut) {
  $env:CURL_CA_BUNDLE     = $certifiOut
  $env:SSL_CERT_FILE      = $certifiOut
  $env:REQUESTS_CA_BUNDLE = $certifiOut
}

$ports = 5001, 5005
foreach ($p in $ports) {
  if (Get-NetTCPConnection -LocalPort $p -State Listen -ErrorAction SilentlyContinue) {
    Write-Warning "port $p is already in use - stop it first (run-worker.ps1 -Stop) if this isn't the right process."
  }
}

function Start-Svc($name, $file, $cmdArgs, $wd, $out, $err) {
  Start-Process -FilePath $file -ArgumentList $cmdArgs -WorkingDirectory $wd `
    -RedirectStandardOutput $out -RedirectStandardError $err -WindowStyle Hidden -PassThru |
    Select-Object @{n='service';e={$name}}, Id
}

Start-Svc 'data-scraper' $venvPython 'app.py' $root `
  "$root\_run_scraper.log" "$root\_run_scraper.err"

Start-Svc 'tm-manager-api' $venvPython 'app.py' "$root\tm_manager" `
  "$root\tm_manager\_run_be.log" "$root\tm_manager\_run_be.err"

# pdf_scraper is optional - app.py already falls back to local save if it's
# unreachable (see app.py's _send_to_pdf_scraper), so a failure here is not
# fatal.
try {
  Start-Svc 'pdf-scraper' $venvPython 'app.py' "$root\pdf_scraper" `
    "$root\pdf_scraper\_run_pdf.log" "$root\pdf_scraper\_run_pdf.err"
} catch {
  Write-Host "  pdf-scraper did not start (non-fatal - the scraper falls back to local save)." -ForegroundColor Yellow
}

Start-Sleep -Seconds 10

# --- 6. Health check -----------------------------------------------------------
Write-Host "[6/6] Health check"
$ok = $true
foreach ($u in @('http://localhost:5001/', 'http://localhost:5005/api/dashboard')) {
  try {
    $r = Invoke-WebRequest $u -UseBasicParsing -TimeoutSec 12
    "{0,-45} {1}" -f $u, $r.StatusCode
  } catch {
    # /api/dashboard requires login (401 is expected and fine - it proves
    # the process is up and routing requests); anything else is a real problem.
    if ($_.Exception.Response -and [int]$_.Exception.Response.StatusCode -eq 401) {
      "{0,-45} 401 (expected - needs login, process is up)" -f $u
    } else {
      "{0,-45} NOT READY (check logs in this folder)" -f $u
      $ok = $false
    }
  }
}

Write-Host ""
if ($ok) {
  Write-Host "=== Setup complete: '$machineKey' is running ===" -ForegroundColor Green
} else {
  Write-Host "=== Setup finished, but a health check failed - check the .err logs in this folder ===" -ForegroundColor Yellow
}
Write-Host ""
Write-Host "Next step: go to $CoordinatorUrl/admin/fleet and assign some OTP accounts to '$machineKey'."
Write-Host "Local status page: http://localhost:5001/status"
Write-Host "To stop/restart later: powershell -ExecutionPolicy Bypass -File .\run-worker.ps1 -Stop  (no flag to start)"
